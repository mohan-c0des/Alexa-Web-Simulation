/**
 * Extracts follow-up questions from the "## Follow-up questions" section
 * of `report_markdown` generated by `analyze_data.py` or `research_topic.py`.
 */
function extractFollowUpPrompts(markdown = '') {
  if (!markdown) return [];
  const match = markdown.match(/## Follow-up questions\s+([\s\S]*?)(?:\n## |\s*$)/i);
  if (!match) return [];
  return match[1]
    .split('\n')
    .map((line) => line.replace(/^[-*]\s*/, '').trim())
    .filter((line) => line.length > 5 && line.length < 140)
    .slice(0, 3);
}

/**
 * Formats markdown text from analyze_data into clean structured sections for the Echo Show UI.
 */
function FormattedMarkdown({ markdown }) {
  if (!markdown) return null;
  const lines = markdown.split('\n');

  return (
    <div className="space-y-2.5 text-slate-300 text-sm leading-relaxed">
      {lines.map((raw, idx) => {
        const line = raw.trim();
        if (!line) return <div key={idx} className="h-1" />;

        if (line.startsWith('# ')) {
          return (
            <h2 key={idx} className="text-lg font-bold text-white tracking-tight pt-1">
              {line.slice(2)}
            </h2>
          );
        }
        if (line.startsWith('## ')) {
          return (
            <h3
              key={idx}
              className="text-xs font-bold uppercase tracking-wider text-cyan-400 pt-3 pb-1 border-b border-slate-800/80"
            >
              {line.slice(3)}
            </h3>
          );
        }
        if (line.startsWith('### ')) {
          return (
            <h4 key={idx} className="text-sm font-semibold text-slate-200 pt-2">
              {line.slice(4)}
            </h4>
          );
        }
        if (line.startsWith('- ') || line.startsWith('* ')) {
          const content = line.slice(2);
          const parts = content.split(/(\*\*.*?\*\*)/g);
          return (
            <div
              key={idx}
              className="flex items-start gap-2.5 bg-slate-900/55 border border-slate-800/70 rounded-lg px-3 py-2"
            >
              <span className="w-1.5 h-1.5 rounded-full bg-cyan-400 mt-2 shrink-0" />
              <div className="text-xs sm:text-sm text-slate-300">
                {parts.map((part, pIdx) =>
                  part.startsWith('**') && part.endsWith('**') ? (
                    <span key={pIdx} className="font-semibold text-white">
                      {part.slice(2, -2)}
                    </span>
                  ) : (
                    <span key={pIdx}>{part}</span>
                  )
                )}
              </div>
            </div>
          );
        }

        const parts = line.split(/(\*\*.*?\*\*)/g);
        return (
          <p key={idx} className="text-xs sm:text-sm text-slate-300">
            {parts.map((part, pIdx) =>
              part.startsWith('**') && part.endsWith('**') ? (
                <span key={pIdx} className="font-semibold text-cyan-300">
                  {part.slice(2, -2)}
                </span>
              ) : (
                <span key={pIdx}>{part}</span>
              )
            )}
          </p>
        );
      })}
    </div>
  );
}

